const path = require('node:path');

function postgresSql(sql) {
  let position = 0;
  return sql.replace(/'(?:''|[^'])*'|"(?:""|[^"])*"|\?/g, token => token === '?' ? `$${++position}` : token);
}

function statements(query, exec) {
  return {
    exec,
    prepare(sql) {
      return {
        all: async (...values) => (await query(sql, values, 'all')).rows,
        get: async (...values) => (await query(sql, values, 'all')).rows[0],
        run: async (...values) => query(sql, values, 'run')
      };
    }
  };
}

function createDatabase({ connectionString = process.env.DATABASE_URL, filename = path.join(__dirname, 'hostel-homes.sqlite') } = {}) {
  if (connectionString) {
    const { Pool } = require('pg');
    const url = new URL(connectionString);
    if (!['postgres:', 'postgresql:'].includes(url.protocol)) throw Error('DATABASE_URL must be a PostgreSQL connection string.');
    // Verify the certificate and hostname when using Neon's TLS connection string.
    if (url.searchParams.get('sslmode') === 'require') url.searchParams.set('sslmode', 'verify-full');
    const pool = new Pool({ connectionString: url.toString(), max: 5, connectionTimeoutMillis: 15000, idleTimeoutMillis: 10000, enableChannelBinding: true });
    pool.on('error', error => console.error(`Database connection interrupted (${error.code || error.name}).`));
    const access = client => statements(async (sql, values) => {
      const result = await client.query(postgresSql(sql), values);
      return { rows: result.rows, changes: result.rowCount, lastInsertRowid: result.rows[0]?.id };
    }, sql => client.query(sql));
    const db = access(pool);
    return Object.assign(db, {
      dialect: 'PostgreSQL',
      async transaction(callback) {
        const client = await pool.connect();
        try {
          await client.query('BEGIN');
          const result = await callback(access(client));
          await client.query('COMMIT');
          return result;
        } catch (error) {
          await client.query('ROLLBACK');
          throw error;
        } finally { client.release(); }
      },
      close: () => pool.end()
    });
  }

  const { DatabaseSync } = require('node:sqlite');
  const sqlite = new DatabaseSync(filename);
  sqlite.exec('PRAGMA journal_mode=WAL; PRAGMA foreign_keys=ON; PRAGMA busy_timeout=5000;');
  let pending = Promise.resolve();
  // A transaction owns the SQLite connection until all its awaited work finishes.
  const serial = callback => {
    const result = pending.then(callback);
    pending = result.catch(() => {});
    return result;
  };
  const direct = statements((sql, values, mode) => {
    const statement = sqlite.prepare(sql);
    return mode === 'all' ? { rows: statement.all(...values) } : { rows: [], ...statement.run(...values) };
  }, sql => sqlite.exec(sql));
  const db = statements((sql, values, mode) => serial(() => direct.prepare(sql)[mode](...values)).then(result => mode === 'all' ? { rows: result } : result), sql => serial(() => direct.exec(sql)));
  return Object.assign(db, {
    dialect: 'SQLite',
    transaction: callback => serial(async () => {
      sqlite.exec('BEGIN IMMEDIATE');
      try {
        const result = await callback(direct);
        sqlite.exec('COMMIT');
        return result;
      } catch (error) { sqlite.exec('ROLLBACK'); throw error; }
    }),
    close: () => serial(() => sqlite.close())
  });
}

async function initializeDatabase(db) {
  const postgres = db.dialect === 'PostgreSQL';
  const id = postgres ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
  const schema = `
    CREATE TABLE IF NOT EXISTS users (id ${id}, name TEXT NOT NULL, email TEXT NOT NULL, password_hash TEXT NOT NULL, role TEXT NOT NULL DEFAULT 'User' CHECK(role IN ('User','Owner','Admin')), created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
    CREATE UNIQUE INDEX IF NOT EXISTS users_email_unique ON users(LOWER(email));
    CREATE TABLE IF NOT EXISTS properties (id ${id}, owner_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, title TEXT NOT NULL, type TEXT NOT NULL, rent NUMERIC NOT NULL CHECK(rent > 0), deposit NUMERIC NOT NULL DEFAULT 0, city TEXT NOT NULL, locality TEXT NOT NULL, facilities TEXT NOT NULL DEFAULT '[]', description TEXT NOT NULL, phone TEXT NOT NULL DEFAULT '', gender TEXT NOT NULL DEFAULT 'Any', image_url TEXT NOT NULL DEFAULT '', availability TEXT NOT NULL DEFAULT 'Available', status TEXT NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Approved','Rejected')), created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
    CREATE TABLE IF NOT EXISTS favourites (user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP, PRIMARY KEY(user_id,property_id));
    CREATE TABLE IF NOT EXISTS enquiries (id ${id}, property_id INTEGER NOT NULL REFERENCES properties(id) ON DELETE CASCADE, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, move_date TEXT NOT NULL, message TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'Pending' CHECK(status IN ('Pending','Contacted','Closed')), created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
    CREATE TABLE IF NOT EXISTS notifications (id ${id}, user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE, property_id INTEGER REFERENCES properties(id) ON DELETE SET NULL, kind TEXT NOT NULL, message TEXT NOT NULL, is_read INTEGER NOT NULL DEFAULT 0 CHECK(is_read IN (0,1)), created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP);
    CREATE INDEX IF NOT EXISTS notifications_user ON notifications(user_id,is_read,id);
  `;
  await db.transaction(async tx => {
    if (postgres) await tx.exec('SELECT pg_advisory_xact_lock(1752390621)');
    await tx.exec(schema);
    const columns = {
      properties: { image_urls: "TEXT NOT NULL DEFAULT '[]'", image_labels: "TEXT NOT NULL DEFAULT '[]'", latitude: 'DOUBLE PRECISION', longitude: 'DOUBLE PRECISION' },
      notifications: { email_sent_at: 'TEXT', email_key: 'TEXT', email_attempts: 'INTEGER NOT NULL DEFAULT 0', email_next_attempt: 'BIGINT NOT NULL DEFAULT 0' }
    };
    for (const [table, additions] of Object.entries(columns)) {
      const existing = postgres ? [] : (await tx.prepare(`PRAGMA table_info(${table})`).all()).map(column => column.name);
      for (const [column, type] of Object.entries(additions)) {
        if (postgres || !existing.includes(column)) await tx.exec(`ALTER TABLE ${table} ADD COLUMN ${postgres ? 'IF NOT EXISTS ' : ''}${column} ${type}`);
      }
    }
  });
}

module.exports = { createDatabase, initializeDatabase };
